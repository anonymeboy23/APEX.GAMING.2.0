create extension if not exists pgcrypto;

-- Profil lié à Supabase Auth. Le rôle admin est contrôlé côté serveur par RLS.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '',
  phone text,
  role text not null default 'customer' check (role in ('customer', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id text primary key,
  name text not null,
  description text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.inventory (
  product_id text primary key references public.products(id) on delete cascade,
  quantity integer not null default 0 check (quantity >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.promotions (
  code text primary key,
  percent integer not null check (percent between 0 and 90),
  active boolean not null default false,
  starts_at timestamptz,
  ends_at timestamptz
);

create table if not exists public.orders (
  id text primary key,
  customer_id uuid references public.profiles(id) on delete set null,
  status text not null default 'En attente de confirmation'
    check (status in ('En attente de confirmation', 'Confirmée', 'En préparation', 'Livrée', 'Annulée')),
  customer_name text not null,
  phone text not null,
  email text,
  note text,
  total numeric(12,2) not null check (total >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id text not null references public.orders(id) on delete cascade,
  product_id text not null references public.products(id),
  region text not null,
  face_value numeric(12,2) not null check (face_value >= 0),
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0)
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  customer_id uuid references public.profiles(id) on delete set null,
  customer_name text not null,
  rating integer not null check (rating between 1 and 5),
  message text not null,
  approved boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists idx_orders_customer on public.orders(customer_id);
create index if not exists idx_orders_status on public.orders(status);
create index if not exists idx_orders_created_at on public.orders(created_at desc);
create index if not exists idx_order_items_order on public.order_items(order_id);
create index if not exists idx_reviews_approved on public.reviews(approved);

-- Profil automatique lors de la création d'un compte Auth.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, phone)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'name', ''),
    new.raw_user_meta_data->>'phone'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_updated_at on public.profiles;
create trigger profiles_updated_at before update on public.profiles
for each row execute procedure public.touch_updated_at();

drop trigger if exists orders_updated_at on public.orders;
create trigger orders_updated_at before update on public.orders
for each row execute procedure public.touch_updated_at();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.inventory enable row level security;
alter table public.promotions enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.reviews enable row level security;

drop policy if exists "profiles own read" on public.profiles;
create policy "profiles own read" on public.profiles for select
  using (id = auth.uid() or public.is_admin());

drop policy if exists "profiles own update" on public.profiles;
create policy "profiles own update" on public.profiles for update
  using (id = auth.uid() or public.is_admin())
  with check (id = auth.uid() or public.is_admin());

drop policy if exists "products public read" on public.products;
create policy "products public read" on public.products for select
  using (active = true or public.is_admin());

drop policy if exists "products admin write" on public.products;
create policy "products admin write" on public.products for all
  using (public.is_admin()) with check (public.is_admin());

drop policy if exists "inventory public read" on public.inventory;
create policy "inventory public read" on public.inventory for select
  using (true);

drop policy if exists "inventory admin write" on public.inventory;
create policy "inventory admin write" on public.inventory for all
  using (public.is_admin()) with check (public.is_admin());

drop policy if exists "promotions public active read" on public.promotions;
create policy "promotions public active read" on public.promotions for select
  using (active = true and (starts_at is null or starts_at <= now())
    and (ends_at is null or ends_at >= now()));

drop policy if exists "promotions admin write" on public.promotions;
create policy "promotions admin write" on public.promotions for all
  using (public.is_admin()) with check (public.is_admin());

drop policy if exists "orders customer create" on public.orders;
create policy "orders customer create" on public.orders for insert
  with check (customer_id is null or customer_id = auth.uid());

drop policy if exists "orders own read" on public.orders;
create policy "orders own read" on public.orders for select
  using (customer_id = auth.uid() or public.is_admin());

drop policy if exists "orders admin update" on public.orders;
create policy "orders admin update" on public.orders for update
  using (public.is_admin()) with check (public.is_admin());

drop policy if exists "order items own read" on public.order_items;
create policy "order items own read" on public.order_items for select
  using (exists (
    select 1 from public.orders o
    where o.id = order_id and (o.customer_id = auth.uid() or public.is_admin())
  ));

drop policy if exists "reviews public approved read" on public.reviews;
create policy "reviews public approved read" on public.reviews for select
  using (approved = true or public.is_admin());

drop policy if exists "reviews customer create" on public.reviews;
create policy "reviews customer create" on public.reviews for insert
  with check (customer_id is null or customer_id = auth.uid());

drop policy if exists "reviews admin moderate" on public.reviews;
create policy "reviews admin moderate" on public.reviews for update
  using (public.is_admin()) with check (public.is_admin());

drop policy if exists "reviews admin delete" on public.reviews;
create policy "reviews admin delete" on public.reviews for delete
  using (public.is_admin());

