create extension if not exists pgcrypto;

-- Profil lié à Supabase Auth. Le rôle admin est contrôlé côté serveur par RLS.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '',
  phone text,
  role text not null default 'customer' check (role in ('customer', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id text primary key,
  name text not null,
  description text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.customer_favorites (
  user_id uuid not null references public.profiles(id) on delete cascade,
  product_id text not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, product_id)
);

create table if not exists public.inventory (
  product_id text primary key references public.products(id) on delete cascade,
  quantity integer not null default 0 check (quantity >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.promotions (
  code text primary key,
  percent integer not null check (percent between 0 and 90),
  active boolean not null default false,
  starts_at timestamptz,
  ends_at timestamptz
);

create table if not exists public.store_settings (
  id boolean primary key default true check (id),
  margin numeric(5,4) not null default 0.60 check (margin between 0 and 5),
  price_round numeric(12,2) not null default 1 check (price_round > 0),
  payment_methods jsonb not null default '[["M-Pesa","XXX XXX XXX"],["Airtel Money","XXX XXX XXX"],["Orange Money","XXX XXX XXX"]]'::jsonb,
  promo_code text not null default '',
  promo_percent integer not null default 0 check (promo_percent between 0 and 90),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id text primary key,
  customer_id uuid references public.profiles(id) on delete set null,
  status text not null default 'En attente de confirmation'
    check (status in ('En attente de confirmation', 'Confirmée', 'En préparation', 'Livrée', 'Annulée')),
  customer_name text not null,
  phone text not null,
  email text,
  note text,
  total numeric(12,2) not null check (total >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id text not null references public.orders(id) on delete cascade,
  product_id text not null references public.products(id),
  region text not null,
  face_value numeric(12,2) not null check (face_value >= 0),
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0)
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  customer_id uuid references public.profiles(id) on delete set null,
  customer_name text not null,
  rating integer not null check (rating between 1 and 5),
  message text not null,
  approved boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists idx_orders_customer on public.orders(customer_id);
create index if not exists idx_orders_status on public.orders(status);
create index if not exists idx_orders_created_at on public.orders(created_at desc);
create index if not exists idx_order_items_order on public.order_items(order_id);
create index if not exists idx_reviews_approved on public.reviews(approved);

-- Profil automatique lors de la création d'un compte Auth.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, phone)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'name', ''),
    new.raw_user_meta_data->>'phone'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_updated_at on public.profiles;
create trigger profiles_updated_at before update on public.profiles
for each row execute procedure public.touch_updated_at();

drop trigger if exists orders_updated_at on public.orders;
create trigger orders_updated_at before update on public.orders
for each row execute procedure public.touch_updated_at();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

create or replace function public.prevent_customer_role_change()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  if new.role is distinct from old.role and not public.is_admin() then
    raise exception 'Only an administrator can change account roles';
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_role_guard on public.profiles;
create trigger profiles_role_guard before update on public.profiles
for each row execute procedure public.prevent_customer_role_change();

-- Administration des rôles depuis l'espace admin, sans exposer service_role au navigateur.
create or replace function public.list_admin_accounts()
returns table(account_email text, account_name text, created_at timestamptz)
language plpgsql
stable
security definer
set search_path = public, auth
as $$
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception 'Administrator access required';
  end if;

  return query
    select u.email::text, coalesce(p.name, ''), p.created_at
    from public.profiles p
    join auth.users u on u.id = p.id
    where p.role = 'admin'
    order by p.created_at;
end;
$$;

create or replace function public.grant_admin_by_email(p_email text)
returns text
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_user_id uuid;
  v_email text;
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception 'Administrator access required';
  end if;

  if p_email is null or length(trim(p_email)) > 320 or trim(p_email) = '' then
    raise exception 'Enter a valid account email';
  end if;

  select u.id, u.email
    into v_user_id, v_email
    from auth.users u
    where lower(u.email) = lower(trim(p_email))
    limit 1;

  if v_user_id is null then
    raise exception 'No account found for this email. Ask the person to create an account first';
  end if;

  insert into public.profiles (id, name, phone, role)
    select v_user_id,
      coalesce(u.raw_user_meta_data->>'name', ''),
      u.raw_user_meta_data->>'phone',
      'admin'
    from auth.users u
    where u.id = v_user_id
  on conflict (id) do update set role = 'admin';

  return v_email;
end;
$$;

revoke all on function public.list_admin_accounts() from public, anon;
revoke all on function public.grant_admin_by_email(text) from public, anon;
grant execute on function public.list_admin_accounts() to authenticated;
grant execute on function public.grant_admin_by_email(text) to authenticated;

create or replace function public.get_storefront_config()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'margin', s.margin,
    'round', s.price_round,
    'pay', s.payment_methods,
    'promo', jsonb_build_object(
      'code', s.promo_code,
      'percent', s.promo_percent,
      'enabled', s.promo_code <> '' and s.promo_percent > 0
    ),
    'products', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', p.id, 'active', p.active,
        'quantity', coalesce(i.quantity, 0)
      ) order by p.id)
      from public.products p
      left join public.inventory i on i.product_id = p.id
    ), '[]'::jsonb)
  )
  from public.store_settings s
  where s.id = true;
$$;

create or replace function public.get_admin_store_config()
